// Recursive structural type so translations must match every key/signature of `en`,
// while allowing different string literal values.
type DeepStringify<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends string
    ? string
    : { readonly [K in keyof T]: DeepStringify<T[K]> };

export type Messages = DeepStringify<typeof en>;
